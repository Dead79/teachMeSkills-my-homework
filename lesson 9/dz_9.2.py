import re


def replace_fio(text):
    # Исключаем слова: подсудимый, следователь, жертва, судья (в разных падежах с любой буквой)
    excluded_words = r'([Пп]одсудимый|[Пп]одсудимая|[Сс]ледователь|[Сс]ледователя|[Сс]ледователю|[Сс]ледователем|[Сс]ледователе|'
    excluded_words += r'[Жж]ертва|[Жж]ертвы|[Жж]ертве|[Жж]ертву|[Жж]ертвой|[Жж]ертве|'
    excluded_words += r'[Сс]удья|[Сс]удьи|[Сс]удье|[Сс]удью|[Сс]удьей|[Сс]удье)\b'

    # Шаблоны для ФИО: полное (3 слова) и сокращенное (2 слова - имя фамилия)
    pattern_full = r'\b(?!' + excluded_words + r')[А-ЯЁ][а-яё]*-?[А-ЯЁ]?[а-яё]*\s+[А-ЯЁ][а-яё]*\s+[А-ЯЁ][а-яё]*\b'
    pattern_short = r'\b(?!' + excluded_words + r')[А-ЯЁ][а-яё]*-?[А-ЯЁ]?[а-яё]*\s+[А-ЯЁ][а-яё]*\b'

    # Сначала заменяем полные ФИО, потом сокращенные
    text = re.sub(pattern_full, 'N', text)
    text = re.sub(pattern_short, 'N', text)

    return text


text = input("Введите текст судебного решения: ")
result = replace_fio(text)
print("\nТекст с замененными ФИО:")
print(result) 